/**
 * @param {string} text
 * @returns {Promise<{tool:string,input:string}>}
 */
export async function chooseTool(text) {
  const response = await askModel([
    {
      role: "system",
      content: ROUTER_SYSTEM_PROMPT
    },
    {
      role: "user",
      content: text
    }
  ]);

  try {
    return JSON.parse(response);
  } catch {
    return { ...DEFAULT_ROUTE };
  }
}

import { normalizeHeader } from "./reader.js";

/**
 * Словарь заголовков отчёта движения товара (выгрузка 1С/BAS): одно поле —
 * все его написания, русские и украинские. Раньше этот список жил двумя
 * копиями — плоским объектом в salesOrder.js и шестью массивами в
 * deadStock.js — и расходился бы при каждой правке.
 *
 * Здесь лежит ТОЛЬКО словарь. Правила сопоставления у модулей разные
 * (salesOrder сканирует первые пять строк и сверяет вхождение в обе стороны,
 * deadStock — одну строку заголовков и только в одну), поэтому их не сводим:
 * это была бы смена поведения.
 */
export const MOVEMENT_LABELS = {
  start: ["начало", "початок"],
  receipt: ["приход", "прихід"],
  expense: ["расход", "розхід", "витрата"],
  retailSales: [
    "отчет о розничных продажах",
    "звіт про роздрібні продажі",
    "розничных продаж",
    "роздрібних продаж"
  ],
  buyerSales: ["продажа покупателю", "продаж покупцю"],
  end: ["конец", "кінець"]
};

/**
 * Те же метки, прогнанные через normalizeHeader. Нужны модулям, которые
 * сравнивают уже нормализованные заголовки и не хотят делать это на каждой
 * строке заново.
 * @type {Record<keyof typeof MOVEMENT_LABELS, string[]>}
 */
export const NORMALIZED_MOVEMENT_LABELS = Object.fromEntries(
  Object.entries(MOVEMENT_LABELS).map(([field, labels]) => [
    field,
    labels.map(normalizeHeader)
  ])
);
